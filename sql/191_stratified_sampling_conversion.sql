CREATE OR REPLACE FUNCTION public.sampled_numeric_field_stats_blocks(p_dataset_id uuid, p_field text, p_aliases jsonb, p_after_row_index bigint, p_limit integer, p_cap integer DEFAULT 50000, p_blocks integer DEFAULT 50)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  WITH page AS MATERIALIZED (
    SELECT x.id, x.data, x.row_index
    FROM (
      SELECT b.lo, b.hi,
             (p_cap::numeric / greatest(count(*) OVER (), 1))::int + 1 AS per_block
      FROM dataset_sample_blocks(p_dataset_id, p_cap, p_blocks) b
    ) blk, LATERAL (
      SELECT f.id, f.data, f.row_index
      FROM dataset_rows_flat f
      WHERE f.dataset_id = p_dataset_id
        AND f.row_index >= blk.lo AND f.row_index < blk.hi
