-- sql/191_stratified_sampling_conversion.sql
-- Finish what sql/188 started: move EVERY sampled_* function off hash order and
-- onto the stratified contiguous-block sample.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- WHY (measured; full rationale in sql/188's header)
--
-- The old sample is the `cap` rows with the smallest hash(id||dataset_id). It is
-- uniformly random and deterministic, but hash order is UNCORRELATED WITH
-- PHYSICAL order, so the 50,000 sampled rows are scattered at random across a
-- ~922MB heap. Cost is therefore decided by buffer-cache residency, not by row
-- count — the same 5,000 rows took 28ms on one dataset and 1,895ms on another
-- purely because of what happened to be cached. Reading 5,000 rows of the same
-- dataset:
--
--     hash order (today)                     2,296ms
--     systematic every-Nth (row_index % N)   full scan + temp spill  <- unusable
--     one contiguous block                     374ms
--     50 stratified contiguous blocks           41ms   <- ~55x
--     200 blocks                               243ms
--
-- And at 1M rows: hash 36.6s vs stratified 4.8s, with stratified staying FLAT as
-- the dataset grows. That flatness is the point — it is the blocker for 1M.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- WHY ALL AT ONCE
--
-- The hash sample and the block sample SELECT DIFFERENT ROWS. If the bulk-rows
-- route served one and the count RPCs walked the other, the rows the client
-- holds and the numbers the server reports would describe different samples —
-- a silent, unfalsifiable disagreement. sql/188 converted `sample_dataset_rows`
-- alone and said so explicitly; this migration converts the remaining 19 so the
-- product is never mixed.
--
-- ⚠️ THE NUMBERS MOVE ONCE. Every sampled figure — theme counts, chart
-- aggregates, statistics, anything already exported into a deck — is computed
-- over the sample, so changing the sample changes them. Owner accepted this
-- explicitly (2026-08-15) in preference to carrying two sampling paths forever.
-- Cached analytics must be invalidated when the CODE that calls these lands.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- SHAPE OF THE CONVERSION
--
-- New names (`<name>_blocks`), NOT in-place replacement, for deploy-order
-- safety: between `npm run migrate` and the code deploy, production runs the OLD
-- code, which keeps calling the hash functions and keeps working. The switch
-- happens with the deploy, and rollback is a code revert — no second migration.
--
-- In each function ONLY TWO THINGS CHANGE:
--   1. the sample walk (the `page` / `scan` CTE), and
--   2. the cursor payload: `last_hash` + `last_id` -> `last_row_index`.
-- Every aggregate CTE that reads from `page` is carried through byte-identically.
-- 18 of the 19 were mechanically uniform and were generated by a script that
-- asserts on shape (a hand-typed signature is the one failure mode that silently
-- samples the wrong rows); `sampled_filtered_rows` is hand-written below because
-- its walk CTE is named `scan` and it uses the hash as an ordering key.
--
-- Signature change, uniformly:
--   p_after_hash bigint, p_after_id bigint   ->   p_after_row_index bigint
--   + trailing p_cap integer DEFAULT 50000, p_blocks integer DEFAULT 50
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ⚠️ A FLAW IN sql/188 THAT THIS FIXES, and does not replicate 19 times.
--
-- sql/188's pager applies the cursor INSIDE the per-block LATERAL:
--
--     WHERE ... AND f.row_index > p_after_row_index
--     ORDER BY f.row_index LIMIT blk.per_block
--
-- so a block is free to hand out a FRESH per_block rows on every page. A block
-- straddling a page boundary therefore contributes up to twice its share, and
-- with cap=50K / page=5K that is ~10 of the 50 blocks over-weighted — exactly
-- the stratification the design is for.
--
-- Here the per-block LIMIT is taken from the BLOCK START and the cursor filters
-- what has already been selected, so the sampled set is
--   S = "the first per_block rows of each block"
-- which is a fixed set independent of how it is paged. Blocks entirely below the
-- cursor are pruned (`blk.hi > p_after_row_index`) so paging stays cheap; the
-- current block re-reads its own prefix, which is bounded by per_block and
-- sequential. sample_dataset_rows_blocks is re-created below with the same fix.
--
-- DETERMINISM is preserved: S is a pure function of (min row_index, max
-- row_index, cap, blocks) — no hashing, no randomness (ARCHITECTURE.md D6).
--
-- All new functions are SECURITY DEFINER over raw tenant rows and therefore
-- carry the sql/190 lockdown block (service_role only).

