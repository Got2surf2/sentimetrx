CREATE OR REPLACE FUNCTION public.sampled_taxonomy_date_series_blocks(p_dataset_id uuid, p_axis text, p_date_field text, p_metric_field text, p_bucket text, p_after_row_index bigint, p_limit integer, p_row_ids bigint[] DEFAULT NULL::bigint[], p_field_key text DEFAULT NULL::text, p_cap integer DEFAULT 50000, p_blocks integer DEFAULT 50)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $$
  WITH fld AS (SELECT taxonomy_field_or_primary(p_dataset_id, p_field_key) AS f),
  page AS MATERIALIZED (
    SELECT x.id, x.data, x.row_index
    FROM (
      SELECT b.lo, b.hi,
             (p_cap::numeric / greatest(count(*) OVER (), 1))::int + 1 AS per_block
      FROM dataset_sample_blocks(p_dataset_id, p_cap, p_blocks) b
    ) blk, LATERAL (
      SELECT f.id, f.data, f.row_index
      FROM dataset_rows_flat f
