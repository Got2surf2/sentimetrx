REVOKE ALL ON FUNCTION public.sampled_theme_topical_page_blocks FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sampled_theme_topical_page_blocks TO service_role;

-- ── The one non-uniform function, hand-written ──────────────────────────────
-- sampled_filtered_rows names its walk CTE `scan` (not `page`) and uses the hash
-- as an ORDERING key in two more places: which matched rows survive
-- p_match_limit, and the order they come back in. Under block sampling the
-- equivalent order is row_index — same intent (a stable, sample-order cut),
-- different key.

CREATE OR REPLACE FUNCTION public.sampled_filtered_rows_blocks(
  p_dataset_id      uuid,
  p_filters         jsonb,
  p_after_row_index bigint,
  p_scan_limit      integer,
  p_match_limit     integer,
  p_cap             integer DEFAULT 50000,
  p_blocks          integer DEFAULT 50
)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $$
  WITH scan AS MATERIALIZED (
    SELECT x.id, x.data, x.row_index
    FROM (
      SELECT b.lo, b.hi,
             (p_cap::numeric / greatest(count(*) OVER (), 1))::int + 1 AS per_block
      FROM dataset_sample_blocks(p_dataset_id, p_cap, p_blocks) b
    ) blk, LATERAL (
      SELECT f.id, f.data, f.row_index
      FROM dataset_rows_flat f
      WHERE f.dataset_id = p_dataset_id
        AND f.row_index >= blk.lo AND f.row_index < blk.hi
      ORDER BY f.row_index
      LIMIT blk.per_block
    ) x
    WHERE blk.hi > p_after_row_index AND x.row_index > p_after_row_index
    ORDER BY x.row_index
    LIMIT p_scan_limit
  ), matched AS MATERIALIZED (
    SELECT s.id, s.data, s.row_index
    FROM scan s
    WHERE public.ana_row_matches_filters(s.data, p_filters)
  )
  SELECT jsonb_build_object(
    'n_scanned', (SELECT count(*) FROM scan),
    'n_matched', (SELECT count(*) FROM matched),
    'rows', COALESCE(
      (SELECT jsonb_agg(m.data ORDER BY m.row_index)
       FROM (SELECT id, data, row_index FROM matched ORDER BY row_index LIMIT p_match_limit) m),
      '[]'::jsonb),
    'last_row_index', (SELECT max(row_index) FROM scan)
  );
$$;

