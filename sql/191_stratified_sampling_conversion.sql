REVOKE ALL ON FUNCTION public.sampled_filtered_rows_blocks FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sampled_filtered_rows_blocks TO service_role;

-- ── Re-create sql/188's bulk sampler with the page-boundary fix ─────────────
-- Same contract and same reserved-key/p_drop_keys behaviour as sql/188; the only
-- change is that the per-block LIMIT is taken from the block start and the
-- cursor is applied outside the LATERAL, so a block straddling a page boundary
-- can no longer hand out a second full per_block allocation. Without this the
-- bulk rows and the count RPCs would drift apart at page boundaries — the exact
-- mixing hazard the all-at-once conversion exists to prevent.

CREATE OR REPLACE FUNCTION public.sample_dataset_rows_blocks(
  p_dataset_id       uuid,
  p_after_row_index  bigint,
  p_limit            int,
  p_cap              int DEFAULT 50000,
  p_blocks           int DEFAULT 50,
  p_drop_keys        text[] DEFAULT '{}'
)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  WITH page AS MATERIALIZED (
    SELECT x.id, x.row_index, x.data
    FROM (
      SELECT b.lo, b.hi,
             (p_cap::numeric / greatest(count(*) OVER (), 1))::int + 1 AS per_block
      FROM dataset_sample_blocks(p_dataset_id, p_cap, p_blocks) b
    ) blk, LATERAL (
      SELECT f.id, f.row_index,
             ((f.data - '_tx' - '_txv' - '_sub') - COALESCE(p_drop_keys, '{}'::text[])) AS data
      FROM dataset_rows_flat f
      WHERE f.dataset_id = p_dataset_id
        AND f.row_index >= blk.lo AND f.row_index < blk.hi
      ORDER BY f.row_index
      LIMIT blk.per_block
    ) x
    WHERE blk.hi > p_after_row_index AND x.row_index > p_after_row_index
    ORDER BY x.row_index
    LIMIT p_limit
  )
  SELECT jsonb_build_object(
    'rows', COALESCE(
      jsonb_agg(jsonb_build_object('id', id, 'row_index', row_index, 'data', data) ORDER BY row_index),
      '[]'::jsonb),
    'last_row_index', (SELECT max(row_index) FROM page)
  ) FROM page;
$$;

COMMENT ON FUNCTION public.sample_dataset_rows_blocks(uuid, bigint, int, int, int, text[]) IS
  'Bulk-row sampler over the sql/188 stratified block set. sql/191 moved the per-block LIMIT to the BLOCK START and applies the cursor outside the LATERAL: previously a block straddling a page boundary handed out a fresh per_block rows on every page, over-weighting roughly one block per page. The sampled set is now "the first per_block rows of each block", independent of how it is paged.';

REVOKE ALL ON FUNCTION public.sample_dataset_rows_blocks(uuid, bigint, int, int, int, text[]) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.sample_dataset_rows_blocks(uuid, bigint, int, int, int, text[]) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sample_dataset_rows_blocks(uuid, bigint, int, int, int, text[]) TO service_role;

